package database

import (
	"context"
	"errors"
	"os"
	"testing"
	"time"

	"github.com/orbito/api-go/internal/platform/database/sqlc"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestDefaultConfig(t *testing.T) {
	cfg := DefaultConfig()
	assert.Equal(t, int32(50), cfg.MaxConns)
	assert.Equal(t, int32(10), cfg.MinConns)
	assert.Equal(t, 1*time.Hour, cfg.MaxConnLifetime)
	assert.Equal(t, 30*time.Minute, cfg.MaxConnIdleTime)
	assert.Equal(t, 1*time.Minute, cfg.HealthCheckPeriod)
}

func TestNewDatabaseInvalidURL(t *testing.T) {
	ctx := context.Background()
	db, err := New(ctx, "invalid-database-url-::::////")
	assert.Error(t, err)
	assert.Nil(t, db)
}

func TestLiveDatabaseConnection(t *testing.T) {
	dbURL := os.Getenv("DATABASE_URL")
	if dbURL == "" {
		dbURL = "postgresql://root:root@localhost:5433/orbito"
	}

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	db, err := New(ctx, dbURL, Config{
		MaxConns:          5,
		MinConns:          1,
		MaxConnLifetime:   10 * time.Minute,
		MaxConnIdleTime:   5 * time.Minute,
		HealthCheckPeriod: 30 * time.Second,
	})
	if err != nil {
		t.Skipf("Skipping live database test: PostgreSQL not accessible at %s: %v", dbURL, err)
		return
	}
	defer db.Close()

	require.NoError(t, db.Ping(ctx))
	require.NotNil(t, db.Pool())
	require.NotNil(t, db.Queries())

	// Test PingDatabase query generated by sqlc
	pingVal, err := db.Queries().PingDatabase(ctx)
	require.NoError(t, err)
	assert.Equal(t, int32(1), pingVal)

	// Test WithTx successful commit
	txErr := db.WithTx(ctx, func(q *sqlc.Queries) error {
		val, err := q.PingDatabase(ctx)
		if err != nil {
			return err
		}
		assert.Equal(t, int32(1), val)
		return nil
	})
	require.NoError(t, txErr)

	// Test WithTx rollback on error
	rollbackErr := db.WithTx(ctx, func(q *sqlc.Queries) error {
		return errors.New("simulated business logic failure")
	})
	assert.Error(t, rollbackErr)
	assert.Contains(t, rollbackErr.Error(), "simulated business logic failure")
}
